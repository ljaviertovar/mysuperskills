// src/app/api/v1/meal-plans/[id]/route.ts
import { requireAuth } from '@/lib/api/auth';
import { etagFor, notModified, requireIfMatch } from '@/lib/api/etag';
import { withApi } from '@/lib/api/handler';
import { assertAcceptsJson, parseJsonBody, parseParams } from '@/lib/api/request';
import { noContent, ok } from '@/lib/api/responses';
import { createMealPlanRepository } from '@/server/meal-plans/repository';
import { deleteMealPlan, getMealPlan, updateMealPlan } from '@/server/meal-plans/service';
import { mealPlanParamsSchema, toMealPlanDto, updateMealPlanBodySchema } from '../contract';

const ROUTE = '/api/v1/meal-plans/[id]';
// RouteContext is a global type generated by `next dev`, `next build` or `next typegen` (Next.js 15.5+).
type Ctx = RouteContext<'/api/v1/meal-plans/[id]'>;
// Platform limit in seconds (must be a literal); keep it above apiConfig.timeouts.handlerMs.
export const maxDuration = 30;

export const GET = withApi<Ctx>(ROUTE, async (req, { params }) => {
  assertAcceptsJson(req);
  const principal = await requireAuth(req);
  const { id } = await parseParams(params, mealPlanParamsSchema);

  const row = await getMealPlan(createMealPlanRepository(principal), id); // 404 when missing OR owned by another tenant
  const etag = etagFor(row.version);
  // 304 without a body when the client already holds this version (If-None-Match).
  return notModified(req, etag) ?? ok(toMealPlanDto(row), { headers: { ETag: etag } });
});

// PATCH = partial update. Plain attribute changes (rename, reassign...) belong here, not in action endpoints.
export const PATCH = withApi<Ctx>(ROUTE, async (req, { params }) => {
  assertAcceptsJson(req);
  const principal = await requireAuth(req);
  const { id } = await parseParams(params, mealPlanParamsSchema);
  const expectedVersion = requireIfMatch(req); // 428 if missing; 412 if stale (checked atomically in the repository)
  const patch = await parseJsonBody(req, updateMealPlanBodySchema);

  const row = await updateMealPlan(createMealPlanRepository(principal), id, patch, expectedVersion);
  return ok(toMealPlanDto(row), { headers: { ETag: etagFor(row.version) } });
});

export const DELETE = withApi<Ctx>(ROUTE, async (req, { params }) => {
  const principal = await requireAuth(req, { roles: ['owner', 'admin'] }); // 403 for members without permission
  const { id } = await parseParams(params, mealPlanParamsSchema);

  await deleteMealPlan(createMealPlanRepository(principal), id);
  return noContent();
});
